package com.nerus.httpsms

import java.net.URI
import java.net.URISyntaxException
import java.net.URLDecoder

/**
 * Helpers for the user-supplied httpSMS server URL.
 *
 * The app never ships with a hard-coded server: every user points it at their own
 * self-hosted API, either by typing the URL or by scanning the login QR code shown in
 * the web dashboard.
 */
object ServerUrl {
    /** Scheme and host of the login QR code: `httpsms://login?server=<url>&key=<api key>`. */
    const val QR_SCHEME = "httpsms"
    const val QR_HOST = "login"
    const val QR_PARAM_SERVER = "server"
    const val QR_PARAM_KEY = "key"

    enum class Validation { VALID, EMPTY, INVALID }

    data class QrLogin(val apiKey: String, val serverUrl: String?)

    /**
     * Trims spaces, then strips trailing "/" and a trailing "/v1" (the API prefix is
     * added by the app), so `https://api.example.com/v1/` becomes `https://api.example.com`.
     */
    fun normalize(input: String?): String {
        var url = input?.trim() ?: return ""
        url = url.trimEnd('/')
        if (url.endsWith("/v1", ignoreCase = true)) {
            url = url.dropLast(3).trimEnd('/')
        }
        return url
    }

    /** Validates an already normalized URL: http(s) scheme, a host, no query or fragment. */
    fun validate(url: String): Validation {
        if (url.isBlank()) {
            return Validation.EMPTY
        }
        val uri = try {
            URI(url)
        } catch (e: URISyntaxException) {
            return Validation.INVALID
        }
        val scheme = uri.scheme?.lowercase()
        if (scheme != "http" && scheme != "https") {
            return Validation.INVALID
        }
        if (uri.host.isNullOrBlank() || uri.rawQuery != null || uri.rawFragment != null) {
            return Validation.INVALID
        }
        return Validation.VALID
    }

    fun isValid(url: String) = validate(url) == Validation.VALID

    /** True when the URL uses plain http:// (API key and messages are not encrypted). */
    fun isInsecure(url: String): Boolean = url.trim().startsWith("http://", ignoreCase = true)

    /** True when the URL points to the phone itself, which is almost always a mistake. */
    fun isLoopback(url: String): Boolean {
        val host = try {
            URI(url.trim()).host?.lowercase()?.trim('[', ']')
        } catch (e: URISyntaxException) {
            null
        } ?: return false
        return host == "localhost" || host.startsWith("127.") || host == "::1" || host == "0.0.0.0"
    }

    /**
     * Parses the contents of a login QR code.
     *
     * - New format: `httpsms://login?server=<url-encoded server URL>&key=<url-encoded API key>`
     *   (`server` is optional) fills both the server URL and the API key.
     * - Old format: the bare API key, which keeps QR codes generated by older dashboards working.
     *
     * Returns null when the QR code does not contain an API key.
     */
    fun parseLoginQr(contents: String?): QrLogin? {
        val text = contents?.trim().orEmpty()
        if (text.isEmpty()) {
            return null
        }

        if (!text.startsWith("$QR_SCHEME:", ignoreCase = true)) {
            return QrLogin(apiKey = text, serverUrl = null)
        }

        val uri = try {
            URI(text)
        } catch (e: URISyntaxException) {
            return null
        }
        if (!QR_HOST.equals(uri.host, ignoreCase = true)) {
            return null
        }

        val params = parseQuery(uri.rawQuery)
        val apiKey = params[QR_PARAM_KEY]?.trim().orEmpty()
        if (apiKey.isEmpty()) {
            return null
        }
        val server = params[QR_PARAM_SERVER]?.let { normalize(it) }?.takeIf { it.isNotEmpty() }
        return QrLogin(apiKey = apiKey, serverUrl = server)
    }

    private fun parseQuery(rawQuery: String?): Map<String, String> {
        if (rawQuery.isNullOrEmpty()) {
            return emptyMap()
        }
        return rawQuery.split('&')
            .filter { it.isNotEmpty() }
            .associate { pair ->
                val index = pair.indexOf('=')
                val name = if (index >= 0) pair.substring(0, index) else pair
                val value = if (index >= 0) pair.substring(index + 1) else ""
                decode(name) to decode(value)
            }
    }

    @Suppress("DEPRECATION")
    private fun decode(value: String): String = try {
        // URLDecoder turns "+" into a space; encodeURIComponent never emits a bare "+",
        // so keep a literal "+" in case the QR code was generated by another tool.
        URLDecoder.decode(value.replace("+", "%2B"), "UTF-8")
    } catch (e: IllegalArgumentException) {
        value
    }
}
